function Button({
  className,
  variant = "default",
  size = "default",
  render,
  asChild,
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariants> & { asChild?: boolean }) {
  // asChild from Radix pattern: render as child element instead of <button>
  const childElement = asChild && props.children
    ? (Array.isArray(props.children) ? props.children[0] : props.children)
    : null;

  if (asChild && childElement && typeof childElement === "object" && "type" in childElement) {
    // Render the child element with button styles applied
    const { children: _, ...restProps } = props;
    return (
      <childElement.type
        {...childElement.props}
        {...restProps}
        data-slot="button"
        className={cn(buttonVariants({ variant, size }), childElement.props?.className, className)}
      />
    );
  }

  return (
    <ButtonPrimitive
      data-slot="button"
      className={cn(buttonVariants({ variant, size, className }))}
      {...(render ? { render } : {})}
      {...props}
    />
  )
}

export { Button, buttonVariants }
